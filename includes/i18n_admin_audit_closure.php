function i18n_admin_audit_closure_phrase_map(string $locale): array
{
    $locale = i18n_normalize_locale($locale);
    if ($locale === I18N_DEFAULT_LOCALE) {
        return [];
    }

    $reportPaths = glob(__DIR__ . DIRECTORY_SEPARATOR . 'i18n_admin_audit_closure_keys*.txt') ?: [];
    $reportPaths[] = dirname(__DIR__) . DIRECTORY_SEPARATOR . 'missing_translations_' . date('Y-m-d') . '.txt';

    $keys = [];
    foreach ($reportPaths as $reportPath) {
        if (is_file($reportPath)) {
            $keys = array_merge($keys, i18n_admin_audit_keys_for_locale($reportPath, $locale));
        }
    }

    $map = [];
    foreach (array_values(array_unique($keys)) as $key) {
        $translated = i18n_admin_audit_translate_key($key, $locale);
        // Only include entries where translation actually differs from the key
        // to avoid overwriting correct translations from earlier layers.
        if ($translated !== $key) {
            $map[$key] = $translated;
        }
    }

    // Always include all exact translations so keys not yet in
    // the audit report files still get translated correctly.
    $exactTranslations = i18n_admin_audit_exact_translations($locale);
    foreach ($exactTranslations as $exactKey => $exactValue) {
        if (!isset($map[$exactKey])) {
            $map[$exactKey] = $exactValue;
        }
    }

    return $map;
}

/**
 * @return string[]
 */
function i18n_admin_audit_keys_for_locale(string $reportPath, string $locale): array
{
    $wantedHeader = 'Missing in ' . strtoupper($locale) . ':';
    $keys = [];
    $active = false;

    foreach (file($reportPath, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
        if (str_starts_with($line, 'Missing in ')) {
            $active = str_starts_with($line, $wantedHeader);
            continue;
        }

        if ($active && str_starts_with($line, '  - ')) {
            $keys[] = substr($line, 4);
        }
    }

    return array_values(array_unique($keys));
}

function i18n_admin_audit_translate_key(string $key, string $locale): string
{
    $exact = i18n_admin_audit_exact_translations($locale);
    if (isset($exact[$key])) {
        return $exact[$key];
    }

    $replacements = i18n_admin_audit_word_map($locale);
    uksort($replacements, static fn(string $a, string $b): int => strlen($b) <=> strlen($a));

    return strtr($key, $replacements);
}

