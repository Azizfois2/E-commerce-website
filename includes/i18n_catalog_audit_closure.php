function i18n_catalog_audit_closure_map(string $locale): array
{
    $locale = i18n_normalize_locale($locale);
    $paths = glob(__DIR__ . DIRECTORY_SEPARATOR . 'i18n_catalog_audit_closure_keys*.txt') ?: [];
    $paths[] = dirname(__DIR__) . DIRECTORY_SEPARATOR . 'missing_catalog_translations_' . date('Y-m-d') . '.txt';

    $keys = [];
    foreach ($paths as $path) {
        if (!is_file($path)) {
            continue;
        }

        foreach (i18n_catalog_audit_keys_for_locale($path, $locale) as $key) {
            $keys[$key] = true;
        }
    }

    $map = [];
    foreach (array_keys($keys) as $key) {
        i18n_catalog_audit_set_nested($map, $key, i18n_catalog_audit_translate_key($key, $locale));
    }

    return $map;
}

/**
 * @return string[]
 */
function i18n_catalog_audit_keys_for_locale(string $path, string $locale): array
{
    $wantedHeader = 'Missing in ' . strtoupper($locale) . ':';
    $keys = [];
    $active = false;

    foreach (file($path, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
        if (str_starts_with($line, 'Missing in ')) {
            $active = str_starts_with($line, $wantedHeader);
            continue;
        }

        if (!$active || !str_starts_with($line, '  - ')) {
            continue;
        }

        $entry = substr($line, 4);
        if (preg_match('/^(.+?) \[[^\]]+\]$/', $entry, $matches) === 1) {
            $keys[] = $matches[1];
        }
    }

    return array_values(array_unique($keys));
}

function i18n_catalog_audit_set_nested(array &$map, string $key, string $value): void
{
    $segments = explode('.', $key);
    $cursor = &$map;

    foreach ($segments as $index => $segment) {
        if ($segment === '') {
            return;
        }

        if ($index === count($segments) - 1) {
            $cursor[$segment] = $value;
            return;
        }

        if (!isset($cursor[$segment]) || !is_array($cursor[$segment])) {
            $cursor[$segment] = [];
        }
        $cursor = &$cursor[$segment];
    }
}

function i18n_catalog_audit_translate_key(string $key, string $locale): string
{
    $source = i18n_catalog_audit_english_label($key);
    $exact = i18n_catalog_audit_exact_translations($locale);
    if (isset($exact[$key])) {
        return $exact[$key];
    }
    if (isset($exact[$source])) {
        return $exact[$source];
    }

    if ($locale === I18N_DEFAULT_LOCALE) {
        return $source;
    }

    $replacements = i18n_catalog_audit_word_map($locale);
    uksort($replacements, static fn(string $a, string $b): int => strlen($b) <=> strlen($a));

    return strtr($source, $replacements);
}

function i18n_catalog_audit_english_label(string $key): string
{
    $last = substr($key, (int) strrpos('.' . $key, '.'));
    $last = trim(str_replace(['_', '-'], ' ', $last));
    $last = preg_replace('/\s+/', ' ', $last) ?? $last;

    $acronyms = [
        '2fa' => '2FA',
        'amd' => 'AMD',
        'api' => 'API',
        'cpu' => 'CPU',
        'csv' => 'CSV',
        'fps' => 'FPS',
        'gpu' => 'GPU',
        'html' => 'HTML',
        'id' => 'ID',
        'mad' => 'MAD',
        'pc' => 'PC',
        'psu' => 'PSU',
        'ram' => 'RAM',
        'rma' => 'RMA',
        'sms' => 'SMS',
    ];

    $words = explode(' ', strtolower($last));
    foreach ($words as &$word) {
        $word = $acronyms[$word] ?? ucfirst($word);
    }
    unset($word);

    return implode(' ', $words);
}

